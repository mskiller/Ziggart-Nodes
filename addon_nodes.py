def _build_vlm_config(
    model: str,
    mmproj: str,
    model_override: str,
    mmproj_override: str,
    gpu_layers: int,
    context_size: int,
    vlm_config: ModelConfig | None,
    label_prefix: str = "model",
) -> ModelConfig:
    if isinstance(vlm_config, ModelConfig):
        return vlm_config
    model_path = _resolve_gguf(model, model_override, f"{label_prefix}_model")
    mmproj_path = _resolve_gguf(mmproj, mmproj_override, f"{label_prefix}_mmproj")
    return ModelConfig(
        model_path=model_path,
        mmproj_path=mmproj_path,
        context_size=int(context_size),
        gpu_layers=int(gpu_layers),
        threads=max(1, (os.cpu_count() or 4) // 2),
        flash_attention=True,
        mmproj_on_gpu=True,
    )


def _describe_crop_with_vlm(
    crop_tensor_3d: torch.Tensor,
    instruction: str,
    max_tokens: int = 160,
    seed: int = 42,
) -> str:
    data_uri = image_to_data_uri(crop_tensor_3d, max_dimension=768)
    messages = [
        {
            "role": "system",
            "content": (
                "You are an expert visual prompt engineer for diffusion detail refinement. "
                "Describe only what is visible in the region concisely and accurately. "
                "Output only the descriptive prompt text without markdown or preamble."
            ),
        },
        {
            "role": "user",
            "content": [
                {"type": "text", "text": instruction},
                {"type": "image_url", "image_url": {"url": data_uri}},
            ],
        },
    ]
    return MODEL_MANAGER.chat(
        messages,
        max_tokens=max_tokens,
        temperature=0.2,
        top_p=0.9,
        top_k=30,
        seed=seed,
        enable_thinking=False,
    )


