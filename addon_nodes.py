def _compute_tile_grid(canvas_w: int, canvas_h: int, tile_size: int, overlap: int) -> list[tuple[int, int, int, int]]:
    """
    Computes mod-8 aligned overlapping tile coordinates (x0, y0, x1, y1) covering
    the entire (canvas_w, canvas_h) image.
    """
    tw = min(canvas_w, max(64, (tile_size // 8) * 8))
    th = min(canvas_h, max(64, (tile_size // 8) * 8))
    stride_x = max(8, tw - overlap)
    stride_y = max(8, th - overlap)

    def _positions(total: int, span: int, stride: int) -> list[int]:
        if span >= total:
            return [0]
        coords = list(range(0, total - span, stride))
        if not coords or coords[-1] + span < total:
            coords.append(total - span)
        return coords

    xs = _positions(canvas_w, tw, stride_x)
    ys = _positions(canvas_h, th, stride_y)
    tiles: list[tuple[int, int, int, int]] = []
    for y0 in ys:
        for x0 in xs:
            tiles.append((x0, y0, x0 + tw, y0 + th))
    return tiles


