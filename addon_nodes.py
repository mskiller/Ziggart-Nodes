def _parse_bboxes_json_payload(
    bboxes_json: str,
    batch_size: int,
    img_w: int,
    img_h: int,
    crop_factor_override: float,
) -> list[dict[str, Any]]:
    """
    Normalizes bboxes_json into a flat list of crop descriptors:
    [{"frame_index": int, "box": (x0, y0, x1, y1), "padded_crop": (cx0, cy0, cx1, cy1)}]
    """
    records: list[dict[str, Any]] = []
    try:
        data = json.loads(bboxes_json) if bboxes_json.strip() else []
    except json.JSONDecodeError:
        boxes = parse_bounding_boxes(bboxes_json, img_w, img_h)
        data = [{"frame_index": 0, "detections": [{"box": list(b)} for b in boxes]}]

    if isinstance(data, dict):
        data = [data]

    if isinstance(data, list):
        for entry in data:
            if isinstance(entry, dict) and "detections" in entry:
                f_idx = min(max(0, int(entry.get("frame_index", 0))), max(0, batch_size - 1))
                for det in entry.get("detections", []):
                    raw_box = det.get("box")
                    if not raw_box or len(raw_box) != 4:
                        continue
                    box_t = (int(raw_box[0]), int(raw_box[1]), int(raw_box[2]), int(raw_box[3]))
                    if crop_factor_override > 0.0 or "padded_crop" not in det:
                        factor = crop_factor_override if crop_factor_override > 0.0 else 1.5
                        padded = crop_with_padding(box_t, img_w, img_h, crop_factor=factor)
                    else:
                        pc = det["padded_crop"]
                        padded = (int(pc[0]), int(pc[1]), int(pc[2]), int(pc[3]))
                    records.append({"frame_index": f_idx, "box": box_t, "padded_crop": padded})
            elif isinstance(entry, (list, tuple)) and len(entry) == 4:
                box_t = (int(entry[0]), int(entry[1]), int(entry[2]), int(entry[3]))
                factor = crop_factor_override if crop_factor_override > 0.0 else 1.5
                padded = crop_with_padding(box_t, img_w, img_h, crop_factor=factor)
                records.append({"frame_index": 0, "box": box_t, "padded_crop": padded})

    return records


class ZiggartCropByBBox:
    """
    Crops detected bounding boxes from an image using bboxes_json and outputs a
    stitch_pipe so modified crops from any ComfyUI workflow can be feathered back in.
    """

    DESCRIPTION = (
        "Extracts mod-8 padded, resolution-standardized crops from bboxes_json and "
        "outputs a stitch_pipe for ZiggartStitchByBBox."
    )
    CATEGORY = "Ziggart/Detector"
    FUNCTION = "crop"
    RETURN_TYPES = ("IMAGE", "MASK", "ZIGGART_STITCH_PIPE")
    RETURN_NAMES = ("cropped_images", "crop_masks", "stitch_pipe")
    OUTPUT_TOOLTIPS = (
        "Batch of cropped regions ready for external processing.",
        "Batch of feathered masks matching the cropped regions.",
        "Stitch metadata pipe required by BBox Feathered Stitch.",
    )

    @classmethod
    def INPUT_TYPES(cls):
        return {
            "required": {
                "image": ("IMAGE", {"tooltip": "Base image or batch."}),
                "bboxes_json": ("STRING", {"default": "[]", "multiline": True}),
                "target_resolution": ("INT", {"default": 768, "min": 64, "max": 2048, "step": 64}),
                "crop_factor_override": (
                    "FLOAT",
                    {
                        "default": 0.0,
                        "min": 0.0,
                        "max": 4.0,
                        "step": 0.1,
                        "tooltip": "0.0 uses padded_crop from bboxes_json; >0.0 recomputes padding from box.",
                    },
                ),
                "skip_upscale_if_larger": ("BOOLEAN", {"default": True}),
                "feather_mask": ("INT", {"default": 16, "min": 0, "max": 128}),
            }
        }

    def crop(
        self,
        image: torch.Tensor,
        bboxes_json: str,
        target_resolution: int = 768,
        crop_factor_override: float = 0.0,
        skip_upscale_if_larger: bool = True,
        feather_mask: int = 16,
    ):
        batch_size, img_h, img_w, _ = image.shape
        records = _parse_bboxes_json_payload(
            bboxes_json, batch_size, img_w, img_h, crop_factor_override
        )

        crops_list: list[torch.Tensor] = []
        masks_list: list[torch.Tensor] = []
        crop_meta: list[dict[str, int]] = []

        for rec in records:
            f_idx = rec["frame_index"]
            cx0, cy0, cx1, cy1 = rec["padded_crop"]
            ch, cw = cy1 - cy0, cx1 - cx0
            if ch <= 0 or cw <= 0:
                continue

            crop_orig = image[f_idx : f_idx + 1, cy0:cy1, cx0:cx1, :]
            max_side = max(ch, cw)
            if skip_upscale_if_larger and max_side >= target_resolution:
                target_w = max(64, (cw // 8) * 8)
                target_h = max(64, (ch // 8) * 8)
            else:
                scale = target_resolution / float(max_side)
                target_w = max(64, int(round(cw * scale / 8.0)) * 8)
                target_h = max(64, int(round(ch * scale / 8.0)) * 8)

            if target_h == ch and target_w == cw:
                crop_high = crop_orig.clone()
            else:
                crop_perm = crop_orig.permute(0, 3, 1, 2)
                crop_high = F.interpolate(
                    crop_perm, size=(target_h, target_w), mode="bicubic", align_corners=False
                ).permute(0, 2, 3, 1).clamp(0.0, 1.0)

            crops_list.append(crop_high)
            scaled_feather = (
                max(1, int(round(feather_mask * (target_w / float(max(1, cw))))))
                if feather_mask > 0
                else 0
            )
            fm = create_feathered_mask(target_w, target_h, feather_radius=scaled_feather)
            masks_list.append(fm.unsqueeze(0))
            crop_meta.append(
                {
                    "frame_index": f_idx,
                    "cx0": cx0,
                    "cy0": cy0,
                    "cx1": cx1,
                    "cy1": cy1,
                    "target_h": target_h,
                    "target_w": target_w,
                }
            )

        batched_crops = standardize_and_batch_crops(crops_list)
        if not masks_list:
            batched_masks = torch.zeros((1, 64, 64), dtype=torch.float32)
        else:
            max_mh = batched_crops.shape[1]
            max_mw = batched_crops.shape[2]
            norm_masks = []
            for m in masks_list:
                if m.shape[1] == max_mh and m.shape[2] == max_mw:
                    norm_masks.append(m)
                else:
                    m_res = F.interpolate(
                        m.unsqueeze(1), size=(max_mh, max_mw), mode="bilinear", align_corners=False
                    ).squeeze(1)
                    norm_masks.append(m_res)
            batched_masks = torch.cat(norm_masks, dim=0)

        stitch_pipe = {
            "base_image": image,
            "crops": crop_meta,
        }
        return (batched_crops, batched_masks, stitch_pipe)


class ZiggartStitchByBBox:
    """
    Blends refined crops back into the original image using the stitch_pipe from
    ZiggartCropByBBox and Gaussian alpha feathering.
    """

    DESCRIPTION = (
        "Stitches modified crops back into their original bounding-box locations "
        "with Gaussian border feathering."
    )
    CATEGORY = "Ziggart/Detector"
    FUNCTION = "stitch"
    RETURN_TYPES = ("IMAGE", "MASK")
    RETURN_NAMES = ("image", "composite_mask")
    OUTPUT_TOOLTIPS = (
        "Full image with modified crops seamlessly blended in.",
        "Full-size composite mask of all stitched regions.",
    )

    @classmethod
    def INPUT_TYPES(cls):
        return {
            "required": {
                "stitch_pipe": ("ZIGGART_STITCH_PIPE",),
                "refined_crops": ("IMAGE",),
                "feather_mask": ("INT", {"default": 16, "min": 0, "max": 128}),
                "blend_opacity": ("FLOAT", {"default": 1.0, "min": 0.0, "max": 1.0, "step": 0.05}),
            }
        }

    def stitch(
        self,
        stitch_pipe: dict[str, Any],
        refined_crops: torch.Tensor,
        feather_mask: int = 16,
        blend_opacity: float = 1.0,
    ):
        base_image: torch.Tensor = stitch_pipe["base_image"]
        crop_meta: list[dict[str, int]] = stitch_pipe.get("crops", [])

        batch_size, img_h, img_w, _ = base_image.shape
        out_image = base_image.clone()
        full_masks = torch.zeros((batch_size, img_h, img_w), dtype=torch.float32)

        if not crop_meta:
            return (out_image, full_masks)

        opacity = float(max(0.0, min(1.0, blend_opacity)))
        num_available = refined_crops.shape[0]

        for idx, meta in enumerate(crop_meta):
            if idx >= num_available:
                break
            f_idx = meta["frame_index"]
            cx0, cy0, cx1, cy1 = meta["cx0"], meta["cy0"], meta["cx1"], meta["cy1"]
            ch, cw = cy1 - cy0, cx1 - cx0
            if ch <= 0 or cw <= 0:
                continue

            crop_tensor = refined_crops[idx : idx + 1]
            if crop_tensor.shape[1] == ch and crop_tensor.shape[2] == cw:
                resized_crop = crop_tensor.clamp(0.0, 1.0)
            else:
                c_perm = crop_tensor.permute(0, 3, 1, 2)
                resized_crop = F.interpolate(
                    c_perm, size=(ch, cw), mode="bicubic", align_corners=False
                ).permute(0, 2, 3, 1).clamp(0.0, 1.0)

            resized_crop = resized_crop.to(device=out_image.device, dtype=out_image.dtype)
            feather_m = (
                create_feathered_mask(cw, ch, feather_radius=feather_mask).to(
                    device=out_image.device, dtype=out_image.dtype
                )
                * opacity
            )
            feather_4d = feather_m.unsqueeze(0).unsqueeze(-1)

            current_rgb = out_image[f_idx : f_idx + 1, cy0:cy1, cx0:cx1, :3]
            refined_rgb = resized_crop[:, :, :, :3]
            out_image[f_idx : f_idx + 1, cy0:cy1, cx0:cx1, :3] = (
                refined_rgb * feather_4d + current_rgb * (1.0 - feather_4d)
            )
            full_masks[f_idx, cy0:cy1, cx0:cx1] = torch.maximum(
                full_masks[f_idx, cy0:cy1, cx0:cx1], feather_m.detach().cpu().float()
            )

        return (out_image, full_masks)


