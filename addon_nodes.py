class ZiggartAutoPromptDetailer(ZiggartDetailerKrea2):
    """
    Detects regions using WeVisOne-VL / GGUF VLM, inspects each cropped region to write
    a tailored micro-prompt, and refines each crop with Krea 2 Turbo.
    """

    DESCRIPTION = (
        "Detects target zones with a GGUF VLM, writes a custom visual prompt for each "
        "individual crop while the VLM is in memory, then unloads the VLM and refines "
        "every crop with Krea 2 Turbo."
    )
    CATEGORY = "Ziggart/Detailer"
    FUNCTION = "auto_refine"
    RETURN_TYPES = ("IMAGE", "IMAGE", "IMAGE", "IMAGE", "MASK", "STRING")
    RETURN_NAMES = (
        "image",
        "cropped_refined",
        "cropped_base",
        "detection_preview",
        "mask",
        "generated_prompts",
    )
    OUTPUT_TOOLTIPS = (
        "Final composited image with auto-prompted refined regions blended.",
        "Batch of high-resolution refined crops.",
        "Batch of base crops before refinement.",
        "Detection preview image with bounding boxes.",
        "Full-size composite mask of refined regions.",
        "JSON list of per-crop prompts generated by the VLM.",
    )

    @classmethod
    def INPUT_TYPES(cls):
        models, projectors = _gguf_files()
        return {
            "required": {
                "image": ("IMAGE", {"tooltip": "Source image or batch to refine."}),
                "model": ("MODEL", {"tooltip": "Krea 2 Turbo diffusion model."}),
                "clip": ("CLIP", {"tooltip": "CLIP text encoder."}),
                "vae": ("VAE", {"tooltip": "VAE encoder/decoder."}),
                "detector_model": (models, {"tooltip": "GGUF VLM for detection and crop captioning."}),
                "detector_mmproj": (projectors, {"tooltip": "Matching mmproj GGUF."}),
                "detection_prompt": (
                    "STRING",
                    {
                        "default": "eyes",
                        "multiline": False,
                        "tooltip": "Object or region to detect (e.g., 'eyes', 'hands', 'face').",
                    },
                ),
                "prompt_instruction": (
                    "STRING",
                    {
                        "default": (
                            "Describe this cropped region in rich visual detail for high-resolution "
                            "image refinement. Focus on texture, lighting, and anatomy. Output only the positive prompt."
                        ),
                        "multiline": True,
                        "tooltip": "Instruction telling the VLM how to write the per-crop positive prompt.",
                    },
                ),
                "base_positive_suffix": (
                    "STRING",
                    {
                        "default": "ultra-detailed, sharp focus, high resolution, 8k",
                        "multiline": True,
                        "tooltip": "Quality tags appended to every VLM-generated crop prompt.",
                    },
                ),
                "detail_negative_prompt": (
                    "STRING",
                    {
                        "default": "blurry, noisy, distorted, low quality, artifacts, deformed",
                        "multiline": True,
                        "tooltip": "Negative prompt applied during crop refinement.",
                    },
                ),
                "crop_factor": (
                    "FLOAT",
                    {"default": 1.5, "min": 1.0, "max": 4.0, "step": 0.1},
                ),
                "target_detail_resolution": (
                    "INT",
                    {"default": 768, "min": 256, "max": 2048, "step": 64},
                ),
                "steps": ("INT", {"default": 8, "min": 1, "max": 100}),
                "cfg": ("FLOAT", {"default": 1.5, "min": 0.0, "max": 20.0, "step": 0.1}),
                "denoise": ("FLOAT", {"default": 0.40, "min": 0.0, "max": 1.0, "step": 0.05}),
                "sampler_name": (SAMPLER_NAMES, {"default": "euler"}),
                "scheduler": (SCHEDULER_NAMES, {"default": "simple"}),
                "seed": ("INT", {"default": 0, "min": 0, "max": 0xFFFFFFFFFFFFFFFF}),
                "max_detections": ("INT", {"default": 2, "min": 1, "max": 20}),
                "feather_mask": ("INT", {"default": 16, "min": 0, "max": 128}),
                "free_vram_after": ("BOOLEAN", {"default": True}),
            },
            "optional": {
                "detector_model_override": ("STRING", {"default": ""}),
                "detector_mmproj_override": ("STRING", {"default": ""}),
                "gpu_layers": ("INT", {"default": -1, "min": -1, "max": 256}),
                "context_size": ("INT", {"default": 4096, "min": 1024, "max": 32768}),
                "use_latent_mask": ("BOOLEAN", {"default": True}),
                "skip_upscale_if_larger": ("BOOLEAN", {"default": True}),
                "vlm_config": ("GGUF_VL_MODEL",),
            },
        }

    def auto_refine(
        self,
        image: torch.Tensor,
        model: Any,
        clip: Any,
        vae: Any,
        detector_model: str,
        detector_mmproj: str,
        detection_prompt: str,
        prompt_instruction: str,
        base_positive_suffix: str,
        detail_negative_prompt: str,
        crop_factor: float,
        target_detail_resolution: int,
        steps: int,
        cfg: float,
        denoise: float,
        sampler_name: str,
        scheduler: str,
        seed: int,
        max_detections: int,
        feather_mask: int,
        free_vram_after: bool,
        detector_model_override: str = "",
        detector_mmproj_override: str = "",
        gpu_layers: int = -1,
        context_size: int = 4096,
        use_latent_mask: bool = True,
        skip_upscale_if_larger: bool = True,
        vlm_config: ModelConfig | None = None,
    ):
        config = _build_vlm_config(
            detector_model,
            detector_mmproj,
            detector_model_override,
            detector_mmproj_override,
            gpu_layers,
            context_size,
            vlm_config,
            label_prefix="detector",
        )

        batch_size, img_h, img_w, _ = image.shape
        final_images: list[torch.Tensor] = []
        detection_previews: list[torch.Tensor] = []
        all_masks: list[torch.Tensor] = []
        cropped_base_list: list[torch.Tensor] = []
        cropped_refined_list: list[torch.Tensor] = []
        generated_prompts_log: list[dict[str, Any]] = []

        # Phase 1: VLM Grounding + Per-Crop Auto-Prompting (single model load)
        batch_boxes: list[list[tuple[int, int, int, int]]] = []
        batch_crop_prompts: list[list[str]] = []

        try:
            for b in range(batch_size):
                frame_3d = image[b]
                boxes, _ = detect_objects_with_vlm(
                    frame_image=frame_3d,
                    model_path=config.model_path,
                    mmproj_path=config.mmproj_path,
                    detection_prompt=detection_prompt,
                    max_detections=max_detections,
                    gpu_layers=config.gpu_layers,
                    context_size=config.context_size,
                    unload_detector_before_sampling=False,
                )
                batch_boxes.append(boxes)
                detection_previews.append(draw_boxes_on_image(frame_3d, boxes, label=detection_prompt))

                frame_prompts: list[str] = []
                if boxes:
                    MODEL_MANAGER.load(config, unload_comfy_models=True)
                    for idx, box in enumerate(boxes):
                        cx0, cy0, cx1, cy1 = crop_with_padding(box, img_w, img_h, crop_factor=crop_factor)
                        crop_3d = frame_3d[cy0:cy1, cx0:cx1, :]
                        vlm_desc = _describe_crop_with_vlm(
                            crop_3d,
                            instruction=prompt_instruction,
                            seed=int((seed + b * 97 + idx * 13) & 0x7FFFFFFF),
                        )
                        suffix = base_positive_suffix.strip()
                        full_pos = f"{vlm_desc}, {suffix}" if (vlm_desc and suffix) else (vlm_desc or suffix)
                        frame_prompts.append(full_pos)
                        generated_prompts_log.append(
                            {
                                "frame_index": b,
                                "detection_id": idx + 1,
                                "box": list(box),
                                "padded_crop": [cx0, cy0, cx1, cy1],
                                "prompt": full_pos,
                            }
                        )
                batch_crop_prompts.append(frame_prompts)
        finally:
            if free_vram_after:
                MODEL_MANAGER.unload()
                release_comfy_vram()

        # Phase 2: Diffusion Refinement with Krea 2 Turbo
        any_detections = any(len(b_boxes) > 0 for b_boxes in batch_boxes)
        neg_cond = None
        if any_detections:
            _, neg_cond = self._encode_prompts(clip, "", detail_negative_prompt)

        for b in range(batch_size):
            frame = image[b : b + 1]
            out_frame = frame.clone()
            full_mask = torch.zeros((img_h, img_w), dtype=torch.float32)
            boxes = batch_boxes[b]
            prompts = batch_crop_prompts[b]

            if not boxes:
                final_images.append(out_frame)
                all_masks.append(full_mask.unsqueeze(0))
                continue

            for idx, box in enumerate(boxes):
                cx0, cy0, cx1, cy1 = crop_with_padding(box, img_w, img_h, crop_factor=crop_factor)
                crop_orig = frame[:, cy0:cy1, cx0:cx1, :]
                ch, cw = cy1 - cy0, cx1 - cx0

                max_side = max(ch, cw)
                if skip_upscale_if_larger and max_side >= target_detail_resolution:
                    target_w = max(64, (cw // 8) * 8)
                    target_h = max(64, (ch // 8) * 8)
                else:
                    scale = target_detail_resolution / float(max_side)
                    target_w = max(64, int(round(cw * scale / 8.0)) * 8)
                    target_h = max(64, int(round(ch * scale / 8.0)) * 8)

                if target_h == ch and target_w == cw:
                    crop_high = crop_orig.clone()
                else:
                    crop_perm = crop_orig.permute(0, 3, 1, 2)
                    crop_high = F.interpolate(
                        crop_perm, size=(target_h, target_w), mode="bicubic", align_corners=False
                    ).permute(0, 2, 3, 1).clamp(0.0, 1.0)

                cropped_base_list.append(crop_high[:, :, :, :3].clone())

                crop_pos_prompt = prompts[idx]
                pos_cond, _ = self._encode_prompts(clip, crop_pos_prompt, detail_negative_prompt)

                latent_noise_mask = None
                if use_latent_mask and feather_mask > 0:
                    scaled_feather = max(1, int(round(feather_mask * (target_w / float(max(1, cw))))))
                    latent_noise_mask = create_feathered_mask(
                        target_w, target_h, feather_radius=scaled_feather
                    ).unsqueeze(0)

                cur_seed = (seed + b * 997 + idx * 31) & 0xFFFFFFFFFFFFFFFF
                refined_high = self._execute_sampling(
                    model=model,
                    clip=clip,
                    vae=vae,
                    crop_tensor=crop_high,
                    positive_prompt=crop_pos_prompt,
                    negative_prompt=detail_negative_prompt,
                    steps=steps,
                    cfg=cfg,
                    sampler_name=sampler_name,
                    scheduler=scheduler,
                    denoise=denoise,
                    seed=cur_seed,
                    pos_cond=pos_cond,
                    neg_cond=neg_cond,
                    noise_mask=latent_noise_mask,
                )
                cropped_refined_list.append(refined_high.clone())

                if refined_high.shape[1] == ch and refined_high.shape[2] == cw:
                    refined_orig = refined_high.clamp(0.0, 1.0)
                else:
                    refined_perm = refined_high.permute(0, 3, 1, 2)
                    refined_orig = F.interpolate(
                        refined_perm, size=(ch, cw), mode="bicubic", align_corners=False
                    ).permute(0, 2, 3, 1).clamp(0.0, 1.0)

                refined_orig = refined_orig.to(device=out_frame.device, dtype=out_frame.dtype)
                feather_m = create_feathered_mask(cw, ch, feather_radius=feather_mask).to(
                    device=out_frame.device, dtype=out_frame.dtype
                )
                feather_4d = feather_m.unsqueeze(0).unsqueeze(-1)

                current_rgb = out_frame[:, cy0:cy1, cx0:cx1, :3]
                blended_rgb = refined_orig[:, :, :, :3] * feather_4d + current_rgb * (1.0 - feather_4d)
                out_frame[:, cy0:cy1, cx0:cx1, :3] = blended_rgb

                full_mask[cy0:cy1, cx0:cx1] = torch.maximum(
                    full_mask[cy0:cy1, cx0:cx1], feather_m.detach().cpu().float()
                )

            final_images.append(out_frame)
            all_masks.append(full_mask.unsqueeze(0))

        return (
            torch.cat(final_images, dim=0),
            standardize_and_batch_crops(cropped_refined_list),
            standardize_and_batch_crops(cropped_base_list),
            torch.cat(detection_previews, dim=0),
            torch.cat(all_masks, dim=0),
            json.dumps(generated_prompts_log, indent=2),
        )


