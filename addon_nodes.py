def _mask_to_bounding_box(mask_2d: torch.Tensor, threshold: float = 0.05) -> tuple[int, int, int, int]:
    """Finds the bounding box (x0, y0, x1, y1) of non-zero pixels in a 2D mask [H, W]."""
    h, w = int(mask_2d.shape[0]), int(mask_2d.shape[1])
    active = torch.nonzero(mask_2d > threshold, as_tuple=False)
    if active.numel() == 0:
        return (0, 0, w, h)
    y0 = int(active[:, 0].min().item())
    y1 = min(h, int(active[:, 0].max().item()) + 1)
    x0 = int(active[:, 1].min().item())
    x1 = min(w, int(active[:, 1].max().item()) + 1)
    if x1 <= x0 or y1 <= y0:
        return (0, 0, w, h)
    return (x0, y0, x1, y1)


