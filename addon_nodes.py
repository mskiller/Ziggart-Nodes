class ZiggartVLMImageCritic:
    """
    Uses a local GGUF VLM to inspect generated images for anatomical or rendering defects,
    localizing problem areas with bounding boxes and generating a repair prompt.
    """

    DESCRIPTION = (
        "Scans images with a local GGUF VLM for diffusion defects (hands, eyes, anatomy, text, "
        "blur) and outputs bounding boxes, a defect mask, a repair prompt, and a boolean pass gate."
    )
    CATEGORY = "Ziggart/LLM"
    FUNCTION = "critique"
    RETURN_TYPES = ("IMAGE", "MASK", "STRING", "STRING", "STRING", "BOOLEAN")
    RETURN_NAMES = (
        "preview_image",
        "defect_mask",
        "bboxes_json",
        "fix_positive_prompt",
        "critique_report",
        "needs_refinement",
    )
    OUTPUT_TOOLTIPS = (
        "Image annotated with detected defect bounding boxes.",
        "Mask covering the detected defect regions.",
        "JSON bounding boxes compatible with BBox Crop and Detailers.",
        "Suggested positive prompt to repair the detected defects.",
        "Structured JSON report with quality score and defect notes.",
        "True if at least one defect was localized and needs refinement.",
    )

    FOCUS_PROMPTS = {
        "all_defects": "anatomical errors, malformed hands or fingers, asymmetrical or blurry eyes, distorted faces, mangled text, or severe rendering artifacts",
        "hands_and_limbs": "malformed hands, extra or fused fingers, broken wrists, or unnatural limb anatomy",
        "faces_and_eyes": "blurry pupils, asymmetrical irises, distorted facial features, or unnatural skin artifacts",
        "text_and_logos": "misspelled, garbled, blurry, or illegible text, lettering, and logos",
        "custom": "visual defects matching the user's custom criteria",
    }

    @classmethod
    def INPUT_TYPES(cls):
        models, projectors = _gguf_files()
        return {
            "required": {
                "image": ("IMAGE", {"tooltip": "Image or batch to inspect."}),
                "model": (models, {"tooltip": "GGUF VLM from models/LLM/GGUF."}),
                "mmproj": (projectors, {"tooltip": "Matching mmproj GGUF."}),
                "inspection_focus": (
                    ["all_defects", "hands_and_limbs", "faces_and_eyes", "text_and_logos", "custom"],
                    {"default": "all_defects"},
                ),
                "crop_factor": ("FLOAT", {"default": 1.5, "min": 1.0, "max": 4.0, "step": 0.1}),
                "max_detections": ("INT", {"default": 4, "min": 1, "max": 20}),
                "feather_mask": ("INT", {"default": 16, "min": 0, "max": 128}),
                "free_vram_after": ("BOOLEAN", {"default": True}),
            },
            "optional": {
                "custom_criteria": (
                    "STRING",
                    {
                        "default": "",
                        "multiline": True,
                        "tooltip": "Custom defect description when inspection_focus is 'custom' (or additional criteria).",
                    },
                ),
                "generation_prompt": (
                    "STRING",
                    {
                        "default": "",
                        "multiline": True,
                        "tooltip": "Optional original prompt to check prompt adherence.",
                    },
                ),
                "model_path_override": ("STRING", {"default": ""}),
                "mmproj_path_override": ("STRING", {"default": ""}),
                "gpu_layers": ("INT", {"default": -1, "min": -1, "max": 256}),
                "context_size": ("INT", {"default": 4096, "min": 1024, "max": 32768}),
                "vlm_config": ("GGUF_VL_MODEL",),
            },
        }

    def critique(
        self,
        image: torch.Tensor,
        model: str,
        mmproj: str,
        inspection_focus: str,
        crop_factor: float,
        max_detections: int,
        feather_mask: int,
        free_vram_after: bool,
        custom_criteria: str = "",
        generation_prompt: str = "",
        model_path_override: str = "",
        mmproj_path_override: str = "",
        gpu_layers: int = -1,
        context_size: int = 4096,
        vlm_config: ModelConfig | None = None,
    ):
        config = _build_vlm_config(
            model,
            mmproj,
            model_path_override,
            mmproj_path_override,
            gpu_layers,
            context_size,
            vlm_config,
        )

        focus_desc = self.FOCUS_PROMPTS.get(inspection_focus, self.FOCUS_PROMPTS["all_defects"])
        if custom_criteria.strip():
            focus_desc = f"{focus_desc}. Specifically check for: {custom_criteria.strip()}"

        batch_size, img_h, img_w, _ = image.shape
        previews: list[torch.Tensor] = []
        masks: list[torch.Tensor] = []
        all_bboxes_data: list[dict[str, Any]] = []
        reports: list[dict[str, Any]] = []
        fix_prompts: list[str] = []
        any_defect_found = False

        try:
            MODEL_MANAGER.load(config, unload_comfy_models=True)
            for b in range(batch_size):
                frame = image[b]
                data_uri = image_to_data_uri(frame, max_dimension=1024)
                adherence_clause = (
                    f"\nIntended generation prompt: \"{generation_prompt.strip()}\""
                    if generation_prompt.strip()
                    else ""
                )
                user_msg = (
                    f"Inspect this image for {focus_desc}.{adherence_clause}\n"
                    "Return a JSON object with keys:\n"
                    "- \"score\": integer quality rating from 1 to 10\n"
                    "- \"issues\": short summary of any defects found (or \"none\")\n"
                    "- \"fix_prompt\": a positive detailer prompt to repair the defects with sharp anatomy and detail\n"
                    "- \"boxes\": array of bounding boxes [x0, y0, x1, y1] normalized 0 to 1000 for each defective region."
                )
                messages = [
                    {
                        "role": "system",
                        "content": (
                            "You are a strict image quality and anatomy critic. Locate defects with bounding "
                            "boxes normalized 0..1000 and respond with valid JSON."
                        ),
                    },
                    {
                        "role": "user",
                        "content": [
                            {"type": "text", "text": user_msg},
                            {"type": "image_url", "image_url": {"url": data_uri}},
                        ],
                    },
                ]
                raw_response = MODEL_MANAGER.chat(
                    messages,
                    max_tokens=384,
                    temperature=0.1,
                    top_p=0.9,
                    top_k=20,
                    seed=42,
                    enable_thinking=False,
                )

                boxes = parse_bounding_boxes(raw_response, img_w, img_h)
                if max_detections > 0:
                    boxes = boxes[:max_detections]

                # Attempt to extract structured fields if JSON is present
                score = 8 if not boxes else 5
                issues = "No major defects localized." if not boxes else "Localized defects requiring refinement."
                fix_prompt = "ultra-detailed, anatomically correct, sharp focus, natural texture, 8k"
                json_match = re.search(r"\{[\s\S]*\}", raw_response)
                if json_match:
                    try:
                        parsed_json = json.loads(json_match.group(0))
                        if isinstance(parsed_json, dict):
                            score = int(parsed_json.get("score", score))
                            issues = str(parsed_json.get("issues", issues))
                            if parsed_json.get("fix_prompt"):
                                fix_prompt = str(parsed_json["fix_prompt"]).strip()
                    except Exception:
                        pass

                if boxes:
                    any_defect_found = True
                fix_prompts.append(fix_prompt)

                preview = draw_boxes_on_image(frame, boxes, label="defect")
                previews.append(preview)

                full_mask = torch.zeros((img_h, img_w), dtype=torch.float32)
                frame_bboxes = []
                for i, box in enumerate(boxes):
                    cx0, cy0, cx1, cy1 = crop_with_padding(box, img_w, img_h, crop_factor=crop_factor)
                    bx0, by0, bx1, by1 = box
                    bw, bh = bx1 - bx0, by1 - by0
                    if feather_mask > 0 and bw > 0 and bh > 0:
                        fm = create_feathered_mask(bw, bh, feather_radius=feather_mask)
                        full_mask[by0:by1, bx0:bx1] = torch.maximum(full_mask[by0:by1, bx0:bx1], fm)
                    else:
                        full_mask[by0:by1, bx0:bx1] = 1.0
                    frame_bboxes.append(
                        {
                            "id": i + 1,
                            "box": list(box),
                            "padded_crop": [cx0, cy0, cx1, cy1],
                            "label": "defect",
                        }
                    )

                masks.append(full_mask.unsqueeze(0))
                all_bboxes_data.append({"frame_index": b, "detections": frame_bboxes})
                reports.append(
                    {
                        "frame_index": b,
                        "score": score,
                        "issues": issues,
                        "fix_prompt": fix_prompt,
                        "defect_count": len(boxes),
                    }
                )
        except EmbeddedLlamaError as exc:
            raise RuntimeError(f"GGUF Quality & Anatomy Critic failed: {exc}") from exc
        finally:
            if free_vram_after:
                MODEL_MANAGER.unload()
                release_comfy_vram()

        return (
            torch.cat(previews, dim=0),
            torch.cat(masks, dim=0),
            json.dumps(all_bboxes_data, indent=2),
            fix_prompts[0] if len(fix_prompts) == 1 else "\n".join(fix_prompts),
            json.dumps(reports, indent=2),
            any_defect_found,
        )


